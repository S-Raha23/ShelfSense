from decimal import Decimal

from django.db.models import Count, Q, Sum
from django.utils import timezone
from drf_spectacular.utils import extend_schema
from rest_framework import mixins, status, viewsets
from rest_framework.decorators import action
from rest_framework.response import Response

from apps.accounts.tenancy import BrandScopedMixin, HasBrand

from .models import Recommendation
from .serializers import RecommendationSerializer, RecommendationSummarySerializer


class RecommendationViewSet(BrandScopedMixin, mixins.ListModelMixin, mixins.RetrieveModelMixin, viewsets.GenericViewSet):
    """Recommendations are generated by the engine; users can only act on them (done / dismiss / reopen)."""

    serializer_class = RecommendationSerializer
    permission_classes = [HasBrand]
    queryset = Recommendation.objects.select_related("product")  # avoids N+1 on product title
    filterset_fields = ["status", "severity", "category", "product", "rule_code"]
    search_fields = ["title", "product__title", "product__asin"]
    ordering_fields = ["severity", "estimated_impact", "created_at"]
    ordering = ["-severity", "-estimated_impact"]

    def _transition(self, request, new_status, allowed_from):
        rec = self.get_object()
        if rec.status not in allowed_from:
            return Response(
                {"detail": f"Cannot move a {rec.status} recommendation to {new_status}."},
                status=status.HTTP_409_CONFLICT,
            )
        rec.status = new_status
        rec.resolved_at = None if new_status == Recommendation.Status.OPEN else timezone.now()
        rec.save(update_fields=["status", "resolved_at", "updated_at"])
        return Response(self.get_serializer(rec).data)

    @extend_schema(request=None)
    @action(detail=True, methods=["post"])
    def complete(self, request, pk=None):
        return self._transition(request, Recommendation.Status.DONE, [Recommendation.Status.OPEN])

    @extend_schema(request=None)
    @action(detail=True, methods=["post"])
    def dismiss(self, request, pk=None):
        return self._transition(request, Recommendation.Status.DISMISSED, [Recommendation.Status.OPEN])

    @extend_schema(request=None)
    @action(detail=True, methods=["post"])
    def reopen(self, request, pk=None):
        rec = self.get_object()
        # Respect the "one open per product+rule" constraint.
        if Recommendation.objects.filter(
            product=rec.product, rule_code=rec.rule_code, status=Recommendation.Status.OPEN
        ).exclude(pk=rec.pk).exists():
            return Response({"detail": "A newer open recommendation already exists."}, status=status.HTTP_409_CONFLICT)
        return self._transition(
            request, Recommendation.Status.OPEN, [Recommendation.Status.DONE, Recommendation.Status.DISMISSED]
        )

    @extend_schema(responses=RecommendationSummarySerializer)
    @action(detail=False, methods=["get"])
    def summary(self, request):
        open_qs = Recommendation.objects.filter(brand=self.brand, status=Recommendation.Status.OPEN)
        agg = open_qs.aggregate(
            open_total=Count("id"),
            high=Count("id", filter=Q(severity=Recommendation.Severity.HIGH)),
            medium=Count("id", filter=Q(severity=Recommendation.Severity.MEDIUM)),
            low=Count("id", filter=Q(severity=Recommendation.Severity.LOW)),
            total_estimated_impact=Sum("estimated_impact"),
        )
        agg["total_estimated_impact"] = agg["total_estimated_impact"] or Decimal("0")
        agg["by_category"] = {
            row["category"]: row["n"] for row in open_qs.values("category").annotate(n=Count("id")).order_by()
        }
        return Response(RecommendationSummarySerializer(agg).data)
